#!/usr/bin/env python3
"""
Write ``src/pycrefine/opcodes/tables.py``: the opcode data of CPython 3.10 to 3.14.

pycrefine decodes the bytecode of a Python version other than the one it runs under (#94), so the
data the ``dis`` module of each version holds (names, argument kinds, inline caches, stack effects,
the texts of ``argrepr``) is kept in the package. This script reads it from one interpreter of each
version; run it again only when a version's tables change.

Usage:
    python quality/generate_opcode_tables.py 3.10=/path/to/python3.10 3.11=python3.11 ...
    (name an interpreter for every version already in tables.py; adding a new version is fine)
    python quality/generate_opcode_tables.py --check 3.10=... (exit 1 when tables.py is out of date)
"""
import json
import os
import subprocess
import sys

OUTPUT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "src", "pycrefine", "opcodes", "tables.py")

# Runs under the interpreter whose tables are wanted; prints one JSON object.
DUMP = r'''
import dis, json, opcode, sys

def names_of(ops):
    return sorted({dis.opname[o] for o in ops})

ops = [dis.opname[i] for i in range(256)]
data = {"version": list(sys.version_info[:2]), "names": [None if n.startswith("<") else n for n in ops],
        "have_argument": dis.HAVE_ARGUMENT}
for kind in ("hasconst", "hasname", "hasjrel", "hasjabs", "haslocal", "hasfree", "hascompare", "hasexc"):
    data[kind] = names_of(getattr(dis, kind, ()))
hasarg = getattr(dis, "hasarg", None)
data["hasarg"] = names_of(hasarg) if hasarg is not None else [dis.opname[i] for i in range(dis.HAVE_ARGUMENT, 256)]
ic = getattr(opcode, "_inline_cache_entries", {})
caches = {}
for i in range(256):
    n = ic.get(dis.opname[i], 0) if isinstance(ic, dict) else (ic[i] if i < len(ic) else 0)
    if n:
        caches[dis.opname[i]] = n
data["caches"] = caches
data["cmp_op"] = list(opcode.cmp_op)
data["nb_ops"] = [s for _, s in getattr(opcode, "_nb_ops", ())]
data["intrinsic_1"] = list(getattr(opcode, "_intrinsic_1_descs", ()))
data["intrinsic_2"] = list(getattr(opcode, "_intrinsic_2_descs", ()))
data["make_function_flags"] = list(getattr(dis, "MAKE_FUNCTION_FLAGS", ()))
data["function_attr_flags"] = list(getattr(dis, "FUNCTION_ATTR_FLAGS", ()))
common = getattr(dis, "_common_constants", ())
data["common_constants"] = [o.__name__ if isinstance(o, type) else repr(o) for o in common]
data["special_method_names"] = list(getattr(dis, "_special_method_names", ()))

def effect(i, name, arg):
    try:
        return dis.stack_effect(i, arg, jump=False)
    except ValueError:
        return None

def runs(values):
    out = []
    for v in values:
        if out and out[-1][0] == v:
            out[-1][1] += 1
        else:
            out.append([v, 1])
    return out

stack = {}
for i in range(256):
    name = dis.opname[i]
    if name.startswith("<"):
        continue
    if name in data["hasarg"]:
        values = [effect(i, name, a) for a in range(256)]
        if all(v is None for v in values):
            continue
        a0, a1 = values[0], values[1]
        if None not in values and all(values[a] == a0 + a * (a1 - a0) for a in range(256)):
            stack[name] = ["lin", a1 - a0, a0]
        else:
            stack[name] = ["rle", runs(values)]
    else:
        v = effect(i, name, None)
        if v is not None:
            stack[name] = ["c", v]
data["stack"] = stack
print(json.dumps(data))
'''

HEADER = '''# pylint: skip-file
"""CPython 3.10 to 3.14 opcode data, read from each version's own ``dis``/``opcode`` modules.

Generated by quality/generate_opcode_tables.py: do not edit by hand. See ``pycrefine.opcodes.decode``.
One JSON object per version, so the file stays small and a regenerated table diffs line by line.
"""
import json
from typing import Any, Dict, Tuple

_JSON = {
'''

FOOTER = '''}

TABLES: Dict[Tuple[int, int], Dict[str, Any]] = {
    (int(key.split(".")[0]), int(key.split(".")[1])): json.loads(text) for key, text in _JSON.items()}
'''


def dump(interpreter):
    out = subprocess.run([interpreter, "-I", "-c", DUMP], check=True, capture_output=True, text=True).stdout
    return json.loads(out)


def render(tables):
    lines = []
    for table in sorted(tables, key=lambda t: t["version"]):
        key = ".".join(str(n) for n in table.pop("version"))
        lines.append(f"    {key!r}: {json.dumps(table, separators=(',', ':'), sort_keys=True)!r},\n")
    return HEADER + "".join(lines) + FOOTER


def stored_versions():
    """The versions ``tables.py`` holds now (none when it does not exist yet)."""
    if not os.path.exists(OUTPUT):
        return set()
    namespace = {"__name__": "tables"}
    with open(OUTPUT, encoding="utf-8") as handle:
        exec(compile(handle.read(), OUTPUT, "exec"), namespace)  # pylint: disable=exec-used
    return set(namespace["TABLES"])


def main(argv):
    check = "--check" in argv
    pairs = [a.split("=", 1) for a in argv if "=" in a]
    if not pairs:
        print(__doc__)
        return 2
    tables = [dump(path) for _, path in pairs]
    reported = [tuple(t["version"]) for t in tables]
    duplicates = sorted({v for v in reported if reported.count(v) > 1})
    if duplicates:
        print("two interpreters report the same version: " + ", ".join("%d.%d" % v for v in duplicates), file=sys.stderr)
        return 2
    missing = sorted(stored_versions() - set(reported))
    if missing:
        # (a new version may be added; one already in the file may not be dropped by leaving its interpreter out)
        print("no interpreter given for " + ", ".join("%d.%d" % v for v in missing)
              + ": tables.py would lose it", file=sys.stderr)
        return 2
    text = render(tables)
    if check:
        with open(OUTPUT, encoding="utf-8") as handle:
            return 0 if handle.read() == text else 1
    with open(OUTPUT, "w", encoding="utf-8") as handle:
        handle.write(text)
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
