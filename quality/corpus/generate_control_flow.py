#!/usr/bin/env python3
"""
Generate the pathological control-flow cases in generated/.

Each case is a loop (``for`` or ``while``) whose body is one more construct (an ``if``/``else``,
a ``try``/``except``, a ``try``/``finally``, a ``with`` block or an inner loop) that ends in a
jump (``break``, ``continue`` or ``return``), with code before and after it, run for a few
inputs. The compiler lays these out very differently across Python versions, which is what
makes them good at finding decompiler bugs.

The output is committed and deterministic: ``python generate_control_flow.py`` rewrites it,
``--check`` fails when the committed files are stale (tests/test_corpus.py runs it).
"""
import sys
from pathlib import Path

OUT = Path(__file__).resolve().parent / "generated"

LOOPS = {
    "for": ("    for i in range(n):\n", "        "),
    "while": ("    i = 0\n    while i < n:\n        i += 1\n", "        "),
}

# Statements that leave the loop body in a way the construct decides: {jump} is replaced.
BODIES = {
    "if": (
        "if i % 3 == 0:\n"
        "{ind}    {jump}\n"
        "{ind}else:\n"
        "{ind}    seen.append(i)\n"
    ),
    "try": (
        "try:\n"
        "{ind}    if i % 3 == 0:\n"
        "{ind}        raise ValueError(i)\n"
        "{ind}    seen.append(i)\n"
        "{ind}except ValueError:\n"
        "{ind}    {jump}\n"
    ),
    "finally": (
        "try:\n"
        "{ind}    if i % 3 == 0:\n"
        "{ind}        {jump}\n"
        "{ind}    seen.append(i)\n"
        "{ind}finally:\n"
        "{ind}    seen.append(-i)\n"
    ),
    "with": (
        "with Guard(seen):\n"
        "{ind}    if i % 3 == 0:\n"
        "{ind}        {jump}\n"
        "{ind}    seen.append(i)\n"
    ),
    "nested": (
        "for j in range(2):\n"
        "{ind}    if (i + j) % 3 == 0:\n"
        "{ind}        {jump}\n"
        "{ind}    seen.append(i * 10 + j)\n"
    ),
}

JUMPS = {"break": "break", "continue": "continue", "return": "return seen"}

HEADER = '''"""Generated by generate_control_flow.py: a {loop} loop, {body} body, {jump}. Do not edit."""


class Guard:
    def __init__(self, seen):
        self.seen = seen

    def __enter__(self):
        self.seen.append("in")
        return self

    def __exit__(self, *exc):
        self.seen.append("out")
        return False


def run(n):
    seen = []
'''

FOOTER = '''    seen.append("end")
    return seen


for size in (0, 1, 4, 7):
    print(size, run(size))
RESULT = run(5)
'''


def render(loop, body, jump):
    head, ind = LOOPS[loop]
    lines = BODIES[body].format(ind=ind, jump=JUMPS[jump]).splitlines()
    # The first line of a template is at the loop-body indent; the rest already carry {ind}.
    text = HEADER.format(loop=loop, body=body, jump=jump) + head
    text += "".join((ind + line if k == 0 else line) + "\n" for k, line in enumerate(lines))
    if jump != "return":
        text += ind + "seen.append('after')\n"
    return text + FOOTER


def cases():
    for loop in LOOPS:
        for body in BODIES:
            for jump in JUMPS:
                yield f"cf_{loop}_{body}_{jump}", render(loop, body, jump)


def main(argv):
    check = "--check" in argv
    OUT.mkdir(exist_ok=True)
    stale = []
    wanted = {}
    for name, text in cases():
        wanted[f"{name}.py"] = text
    for fname, text in wanted.items():
        path = OUT / fname
        if check:
            if not path.exists() or path.read_text(encoding="utf-8") != text:
                stale.append(fname)
        else:
            path.write_text(text, encoding="utf-8")
    extra = sorted(p.name for p in OUT.glob("*.py") if p.name not in wanted)
    if check:
        for fname in stale:
            print(f"stale or missing: {fname}", file=sys.stderr)
        for fname in extra:
            print(f"not generated any more: {fname}", file=sys.stderr)
        return 1 if (stale or extra) else 0
    for fname in extra:
        (OUT / fname).unlink()
    print(f"wrote {len(wanted)} cases to {OUT}")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
